package org.binaryinternals.format.classfile;

import java.lang.reflect.AccessFlag.Location;
import java.lang.reflect.ClassFileFormatVersion;
import java.util.Arrays;
import java.util.EnumSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Collectors;
import org.binaryinternals.commonlib.BytesTool;
import org.binaryinternals.format.classfile.attribute.InnerClasses_attribute;
import org.binaryinternals.format.classfile.attribute.MethodParameters_attribute;
import org.binaryinternals.format.classfile.attribute.Module_attribute;

/// Access flags are mask of flags used to denote access permissions to and
/// properties of this class file.
///
/// @author Amos Shi
///
/// ```
/// java:S2386 - Mutable fields should not be "public static" --- We keep the simplied public variable
/// ```
@SuppressWarnings("java:S2386")
public enum AccessFlag {

    /// Declared `public`; may be accessed from outside its package.
    ACC_PUBLIC(java.lang.reflect.AccessFlag.PUBLIC.mask(), JavaLangSpec.Keyword.PUBLIC.text),
    /// Declared `private`; usable only within the defining class.
    ACC_PRIVATE(java.lang.reflect.AccessFlag.PRIVATE.mask(), JavaLangSpec.Keyword.PRIVATE.text),
    /// Declared `protected`; may be accessed within subclasses.
    ACC_PROTECTED(java.lang.reflect.AccessFlag.PROTECTED.mask(), JavaLangSpec.Keyword.PROTECTED.text),
    /// Declared `static`.
    ACC_STATIC(java.lang.reflect.AccessFlag.STATIC.mask(), JavaLangSpec.Keyword.STATIC.text),
    /// Declared `final`; no subclasses allowed.
    ACC_FINAL(java.lang.reflect.AccessFlag.FINAL.mask(), JavaLangSpec.Keyword.FINAL.text),
    /// Indicates that this module ({@link Module_attribute}) is open.
    ACC_OPEN(java.lang.reflect.AccessFlag.OPEN.mask(), JavaLangSpec.ContextualKeyword.OPEN.keyword),
    /// Treat superclass methods specially when invoked by the
    /// `invokespecial` instruction.
    ACC_SUPER(java.lang.reflect.AccessFlag.SUPER.mask(), JavaLangSpec.Keyword.SUPER.text),
    /// Declared `synchronized`; invocation is wrapped by a monitor
    /// use.
    ACC_SYNCHRONIZED(java.lang.reflect.AccessFlag.SYNCHRONIZED.mask(), JavaLangSpec.Keyword.SYNCHRONIZED.text),
    /// Indicates that any module which depends on the current module, implicitly
    /// declares a dependence on the module indicated by this entry.
    ACC_TRANSITIVE(java.lang.reflect.AccessFlag.TRANSITIVE.mask(), JavaLangSpec.ContextualKeyword.TRANSITIVE.keyword),
    /// Declared `volatile`; cannot be cached.
    ACC_VOLATILE(java.lang.reflect.AccessFlag.VOLATILE.mask(), JavaLangSpec.Keyword.VOLATILE.text),
    /// A bridge method, generated by the compiler.
    ACC_BRIDGE(java.lang.reflect.AccessFlag.BRIDGE.mask(), "ACC_BRIDGE"),
    /// Indicates that this dependence is mandatory in the static phase, i.e., at
    /// compile time, but is optional in the dynamic phase, i.e., at run time.
    ACC_STATIC_PHASE(java.lang.reflect.AccessFlag.STATIC_PHASE.mask(), "ACC_STATIC_PHASE"),
    /// Declared `transient`; not written or read by a persistent
    /// object manager.
    ACC_TRANSIENT(java.lang.reflect.AccessFlag.TRANSIENT.mask(), JavaLangSpec.Keyword.TRANSIENT.text),
    /// Declared with variable number of arguments.
    ACC_VARARGS(java.lang.reflect.AccessFlag.VARARGS.mask(), "ACC_VARARGS"),
    /// Declared `native`; implemented in a language other than Java.
    ACC_NATIVE(java.lang.reflect.AccessFlag.NATIVE.mask(), JavaLangSpec.Keyword.NATIVE.text),
    /// Is an interface, not a class.
    ACC_INTERFACE(java.lang.reflect.AccessFlag.INTERFACE.mask(), JavaLangSpec.Keyword.INTERFACE.text),
    /// Declared `abstract`; must not be instantiated.
    ACC_ABSTRACT(java.lang.reflect.AccessFlag.ABSTRACT.mask(), JavaLangSpec.Keyword.ABSTRACT.text),
    /// Declared `strictfp`; floating-point mode is FP-strict.
    ACC_STRICT(java.lang.reflect.AccessFlag.STRICT.mask(), JavaLangSpec.Keyword.STRICTFP.text),
    /// Declared `synthetic`; not present in the source code.
    ///
    /// Indicates that this module ({@link Module_attribute}) was not explicitly
    /// or implicitly declared.
    ///
    /// Indicates that this dependence was not explicitly or implicitly declared
    /// in the source of the module declaration.
    ///
    /// Indicates that this export was not explicitly or implicitly declared in
    /// the source of the module declaration.
    ///
    /// Indicates that this opening was not explicitly or implicitly declared in
    /// the source of the module declaration.
    ACC_SYNTHETIC(java.lang.reflect.AccessFlag.SYNTHETIC.mask(), "ACC_SYNTHETIC"),
    /// Declared as an annotation type.
    ACC_ANNOTATION(java.lang.reflect.AccessFlag.ANNOTATION.mask(), "@interface"),
    /// Declared as an `enum` type.
    ACC_ENUM(java.lang.reflect.AccessFlag.ENUM.mask(), JavaLangSpec.Keyword.ENUM.text),
    /// Is a module, not a class or interface.
    ACC_MODULE(java.lang.reflect.AccessFlag.MODULE.mask(), JavaLangSpec.ContextualKeyword.MODULE.keyword),
    /// Indicates that the formal parameter was implicitly declared in source
    /// code, according to the specification of the language in which the source
    /// code was written (JLS §13.1). (The formal parameter is mandated by a
    /// language specification, so all compilers for the language must emit it.)
    ///
    /// Indicates that this module was implicitly declared.
    ///
    /// Indicates that this dependence was implicitly declared in the source of
    /// the module declaration.
    ///
    /// Indicates that this export was implicitly declared in the source of the
    /// module declaration.
    ///
    /// Indicates that this opening was implicitly declared in the source of the
    /// module declaration.
    ACC_MANDATED(java.lang.reflect.AccessFlag.MANDATED.mask(), "ACC_MANDATED"),
    /// Constructor method (class or instance initializer).
    /// Used by Android dex.
    ACC_CONSTRUCTOR(0x10000, "ACC_CONSTRUCTOR"),
    /// Declared `synchronized`.
    /// Used by Android dex.
    ACC_DECLARED_SYNCHRONIZED(0x20000, "ACC_DECLARED_SYNCHRONIZED");

    /// Binary value in the {@link ClassFile}.
    public final long value;

    /// Modifier in the java source file. Some modifier does not exist in the
    /// source file but generated by compiler.
    public final String modifier;

    /// Modifiers for {@link ClassFile}.
    public static final List<AccessFlag> ForClass = forLocation(Location.CLASS);
    /// Modifiers for {@link field_info}.
    public static final List<AccessFlag> ForField = forLocation(Location.FIELD);
    /// Modifiers for {@link InnerClasses_attribute}.
    public static final List<AccessFlag> ForInnerClass = forLocation(Location.INNER_CLASS);
    /// Modifiers for {@link method_info}.
    public static final List<AccessFlag> ForMethod = forLocation(Location.METHOD);
    /// Modifiers for {@link MethodParameters_attribute}.
    public static final List<AccessFlag> ForMethodParameters = forLocation(Location.METHOD_PARAMETER);
    /// {@link Module_attribute#module_flags} for {@link Module_attribute}.
    public static final List<AccessFlag> ForModule = forLocation(Location.MODULE);
    /// {@link Module_attribute.Exports#exports_flags} for
    /// {@link Module_attribute.Exports}.
    public static final List<AccessFlag> ForModuleExports = forLocation(Location.MODULE_EXPORTS);
    /// {@link Module_attribute.Opens#opens_flags} for
    /// {@link Module_attribute.Opens}.
    public static final List<AccessFlag> ForModuleOpens = forLocation(Location.MODULE_OPENS);
    /// {@link Module_attribute.Requires#requires_flags} for
    /// {@link Module_attribute.Requires}.
    public static final List<AccessFlag> ForModuleRequires = forLocation(Location.MODULE_REQUIRES);

    /// @param i Value in the Class file
    /// @param m Modifier in the java source file
    private AccessFlag(long i, String m) {
        this.value = i;
        this.modifier = m;
    }

    /// The flags allowed at `location` in any class file version, as
    /// defined by {@link java.lang.reflect.AccessFlag}, in the order of this
    /// enum.
    private static List<AccessFlag> forLocation(final Location location) {
        final Set<java.lang.reflect.AccessFlag> allowed = EnumSet.noneOf(java.lang.reflect.AccessFlag.class);
        for (ClassFileFormatVersion version : ClassFileFormatVersion.values()) {
            allowed.addAll(location.flags(version));
        }
        return Arrays.stream(values())
                .filter(flag -> flag.toJdkFlag().filter(allowed::contains).isPresent())
                .toList();
    }

    /// Get the corresponding {@link java.lang.reflect.AccessFlag}.
    ///
    /// @return The JDK access flag, or empty for the flags used by Android dex
    /// only
    public Optional<java.lang.reflect.AccessFlag> toJdkFlag() {
        try {
            return Optional.of(java.lang.reflect.AccessFlag.valueOf(this.name().substring("ACC_".length())));
        } catch (IllegalArgumentException _) {
            return Optional.empty();
        }
    }

    /// Get `int` value of {@link #value}.
    ///
    /// @return `int` value of {@link #value}
    public int intValue() {
        return Math.toIntExact(this.value);
    }

    /// Check if the the `accFlags` matches the access flag or not.
    ///
    /// @param accFlags the access flags value
    /// @return `true` if the access flag matches the
    /// `accFlags`, else `false`
    public boolean match(long accFlags) {
        return (accFlags & this.value) > 0;
    }

    @Override
    public String toString() {
        return "%s value=%s modifier=%s".formatted(name(), BytesTool.getBinaryString(this.value), this.modifier);
    }

    /// Get the modifiers text for a {@link ClassFile}.
    ///
    /// @param value Value in the Class file
    /// @return Modifier text
    public static String getClassModifier(long value) {
        return getModifier(value, AccessFlag.ForClass);
    }

    /// Get the modifiers text for a {@link field_info}.
    ///
    /// @param value Value in the Class file
    /// @return Modifier text
    public static String getFieldModifier(long value) {
        return getModifier(value, AccessFlag.ForField);
    }

    /// Get the modifiers text for a {@link method_info}.
    ///
    /// @param value Value in the Class file
    /// @return Modifier text
    public static String getMethodModifier(long value) {
        return getModifier(value, AccessFlag.ForMethod);
    }

    /// Get the modifiers text for a {@link InnerClasses_attribute}.
    ///
    /// @param value Value in the Class file
    /// @return Modifier text
    public static String getInnerClassModifier(long value) {
        return getModifier(value, AccessFlag.ForInnerClass);
    }

    /// Get the modifiers text for a {@link MethodParameters_attribute}.
    ///
    /// @param value Value in the Class file
    /// @return Modifier text
    public static String getMethodParametersModifier(long value) {
        return getModifier(value, AccessFlag.ForMethodParameters);
    }

    public static String getModifier(long value, List<AccessFlag> list) {
        return list.stream()
                .filter(flag -> flag.match(value))
                .map(flag -> flag.modifier)
                .collect(Collectors.joining(" "));
    }
}
